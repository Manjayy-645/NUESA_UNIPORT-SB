'use server'

import { createClient } from '@/lib/supabase/server'
import { redirect } from 'next/navigation'

export async function login(formData: FormData) {
  const email = formData.get('email') as string
  const password = formData.get('password') as string
  
  const supabase = await createClient()
  
  const { error } = await supabase.auth.signInWithPassword({
    email,
    password,
  })

  if (error) {
    return { error: error.message }
  }

  // Redirect to portal (middleware will decide if onboarding is needed)
  redirect('/portal')
}

export async function signup(formData: FormData) {
  const email = formData.get('email') as string
  const password = formData.get('password') as string
  
  const supabase = await createClient()
  
  const { error } = await supabase.auth.signUp({
    email,
    password,
    options: {
      // In production, you might require email verification.
      // For this prototype, we'll assume auto-confirm is enabled or they can log in immediately.
    }
  })

  if (error) {
    return { error: error.message }
  }

  // Redirect to portal
  redirect('/portal')
}
